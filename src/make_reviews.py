"""Генерация учебного корпуса отзывов (data/reviews.csv) для ПР-6.

Корпус СИНТЕТИЧЕСКИЙ: отзывы собираются из готовых фраз. Для реалистичности добавлены
смешанные отзывы (положительный с жалобой и наоборот), фразы с отрицанием («не плохо»),
рейтинг-цифры (иногда противоречащие тексту) и 4% случайных ошибок разметки.
Запуск:  python src/make_reviews.py
"""
import random
import pandas as pd

random.seed(7)
POS = [
    "Очень доволен покупкой, всё работает отлично", "Доставка пришла быстрее, чем обещали",
    "Курьер вежливый, заказ привезли горячим", "Качество на высоте, рекомендую всем",
    "Обслуживание превосходное, обязательно вернусь",
    "Цена приятно удивила, соотношение цены и качества отличное",
    "Приложение удобное и быстрое", "Персонал приветливый, всё чисто и уютно",
    "Товар полностью соответствует описанию", "Остались только положительные впечатления",
    "Не ожидал такого качества за эти деньги", "Не пожалел ни разу, что купил",
    "Совсем не плохо, даже лучше, чем ожидал", "Спасибо за быструю и чёткую работу",
    "Лучший сервис, которым пользовался", "Купил маме, она в полном восторге",
]
NEG = [
    "Ужасное качество, разочарован", "Доставку ждал две недели, никто не отвечал",
    "Курьер грубил, заказ привезли холодным", "Не рекомендую, деньги на ветер",
    "Обслуживание отвратительное, больше не приду",
    "Цена завышена, качество не соответствует", "Приложение постоянно вылетает и тормозит",
    "Персонал невежливый, в зале грязно", "Товар не соответствует описанию, пришлось возвращать",
    "Остались только негативные впечатления", "Не понравилось абсолютно ничего",
    "Ничего хорошего сказать не могу", "Не работает с первого дня, вернул обратно",
    "Служба поддержки игнорирует обращения", "Хуже сервиса я не встречал",
    "Сломалось через 3 дня, гарантию не признали",
]
INTROS = ["Заказывал 3 раза.", "Пользуюсь уже 2 месяца.", "Брал на прошлой неделе.", "Купили всей семьёй.", "Отзыв после 10 дней использования."]

rows = []
for _ in range(600):
    label = 1 if random.random() < 0.56 else 0               # 1 — положительный, 0 — отрицательный
    own, other = (POS, NEG) if label else (NEG, POS)
    clauses = random.sample(own, random.choice([2, 3]))
    if random.random() < 0.30:                                 # смешанный отзыв
        clauses.insert(random.randint(0, len(clauses)), random.choice(other))
    random.shuffle(clauses)
    text = ". ".join(clauses) + random.choice([".", "!", "!!", "..."])
    if random.random() < 0.4:
        text = random.choice(INTROS) + " " + text
    if random.random() < 0.25:                                 # рейтинг (иногда противоречит тексту)
        stars = random.choice([4, 5] if label else [1, 2])
        if random.random() < 0.10:
            stars = 6 - stars
        text += f" Оценка: {stars} из 5."
    if random.random() < 0.04:                                 # ошибка разметки
        label = 1 - label
    rows.append((text, label))

pd.DataFrame(rows, columns=["text", "label"]).to_csv("data/reviews.csv", index=False, encoding="utf-8")
print("Сохранено:", len(rows))
